def rule_name(rule):
    """0x4D / "4D" / "rule 4D" -> "SINGLE EXTREME RULES MATCH" (None: not a rule id)"""
    if isinstance(rule, str):
        m = re.fullmatch(r"\s*(?:rule\s+)?(?:0x)?([0-9A-Fa-f]{1,2})\s*", rule)
        if not m:
            return None
        rule = int(m.group(1), 16)
    return RULES.get(rule)


def view_name(view):
    return VIEWS.get(view)
